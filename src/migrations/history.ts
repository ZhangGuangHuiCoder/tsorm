import { createHash, randomUUID } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Connection } from './provider.js';
import { MigrationError } from './errors.js';
import { HISTORY_TABLE } from './introspect.js';

/** One migration file, `<YYYYMMDDHHMMSS>_<name>.sql`; `name` is the file name without `.sql`. */
export interface LocalMigration {
  name: string;
  path: string;
  sql: string;
  checksum: string;
}
interface HistoryRow {
  id: string;
  checksum: string;
  migration_name: string;
  logs: string | null;
  started_at: string;
  finished_at: string | null;
  rolled_back_at: string | null;
  applied_steps_count: number;
}
export const isApplied = (r: HistoryRow) => r.finished_at !== null && r.rolled_back_at === null;
export const isFailed = (r: HistoryRow) => r.finished_at === null && r.rolled_back_at === null;

const checksum = (sql: string) => createHash('sha256').update(sql).digest('hex');
/** Checksums ignore CRLF/LF differences introduced by Git. */
const sameChecksum = (stored: string, sql: string) =>
  stored === checksum(sql) || stored === checksum(sql.replaceAll('\r\n', '\n'));
export const modified = (row: HistoryRow, local: LocalMigration) => !sameChecksum(row.checksum, local.sql);

const LOCK_FILE = 'migration_lock.toml';

/** `<YYYYMMDDHHMMSS UTC>_<name>.sql`, as in Phinx / ThinkPHP. */
const FILE_NAME = /^(\d{14})_[A-Za-z0-9_]+\.sql$/;

export function readLocalMigrations(directory: string): LocalMigration[] {
  if (!existsSync(directory)) return [];
  const files = readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith('.sql'))
    .map((entry) => entry.name)
    .sort();
  const seen = new Map<string, string>();
  for (const file of files) {
    const stamp = FILE_NAME.exec(file)?.[1];
    if (!stamp)
      throw new MigrationError(
        'INVALID_MIGRATION_FILE',
        `Migration files are named <YYYYMMDDHHMMSS>_<name>.sql: ${file}`,
      );
    if (seen.has(stamp))
      throw new MigrationError(
        'MIGRATION_TIMESTAMP_CONFLICT',
        `${file} and ${seen.get(stamp)} have the same timestamp. Rename one of them so each timestamp is unique.`,
      );
    seen.set(stamp, file);
  }
  return files.map((file) => {
    const path = join(directory, file);
    const sql = readFileSync(path, 'utf8');
    return { name: file.slice(0, -4), path, sql, checksum: checksum(sql) };
  });
}

/** Current UTC time as YYYYMMDDHHMMSS. */
export const timestamp = (date = new Date()) => date.toISOString().replace(/\D/g, '').slice(0, 14);

/** Records the provider id in the lock file; a different id means a different database. */
export function checkLock(directory: string, providerId: string): void {
  const path = join(directory, LOCK_FILE);
  if (!existsSync(path)) return;
  const expected = /^\s*provider\s*=\s*"([^"]*)"/m.exec(readFileSync(path, 'utf8'))?.[1];
  if (expected && expected !== providerId)
    throw new MigrationError(
      'PROVIDER_MISMATCH',
      `The datasource provider \`${providerId}\` does not match \`${expected}\` specified in ${LOCK_FILE}. Remove the migrations directory and start a new migration history.`,
    );
}

export function writeMigration(
  directory: string,
  providerId: string,
  name: string,
  sql: string,
  existing: LocalMigration[],
): LocalMigration {
  const slug = name.replace(/[^A-Za-z0-9_]/g, '_');
  const stamp = timestamp();
  const latest = existing.at(-1)?.name;
  if (latest && latest.slice(0, 14) >= stamp)
    throw new MigrationError(
      'MIGRATION_TIMESTAMP_CONFLICT',
      `The latest migration ${latest} is not older than the current time ${stamp}. Wait a second and retry, or check the system clock and the migration file names.`,
    );
  const file = `${stamp}_${slug}.sql`;
  if (Buffer.byteLength(file) > 200)
    throw new MigrationError(
      'MIGRATION_NAME_TOO_LONG',
      'The migration file name must not be longer than 200 characters (bytes)',
    );
  mkdirSync(directory, { recursive: true });
  writeFileSync(join(directory, file), sql);
  const lock = join(directory, LOCK_FILE);
  if (!existsSync(lock))
    writeFileSync(
      lock,
      `# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "${providerId}"\n`,
    );
  return { name: file.slice(0, -4), path: join(directory, file), sql, checksum: checksum(sql) };
}

export function historyExists(conn: Connection): Promise<boolean> {
  return conn.provider.historyExists(conn);
}

export async function ensureHistory(conn: Connection): Promise<void> {
  await conn.script(conn.provider.historyDDL);
}

const text = (value: unknown) =>
  value === null || value === undefined
    ? null
    : value instanceof Date
      ? value.toISOString()
      : String(value);

export async function readHistory(conn: Connection): Promise<HistoryRow[]> {
  if (!(await historyExists(conn))) return [];
  const q = conn.provider.quote;
  const rows = await conn.query(
    `SELECT id, checksum, migration_name, logs, started_at, finished_at, rolled_back_at, applied_steps_count FROM ${q(HISTORY_TABLE)} ORDER BY started_at ASC, migration_name ASC`,
  );
  return rows.map((r) => ({
    id: r.id,
    checksum: r.checksum,
    migration_name: r.migration_name,
    logs: r.logs ?? null,
    started_at: text(r.started_at)!,
    finished_at: text(r.finished_at),
    rolled_back_at: text(r.rolled_back_at),
    applied_steps_count: Number(r.applied_steps_count),
  }));
}

/** Runs a script atomically where the database allows it. */
export function runScript(conn: Connection, sql: string): Promise<void> {
  return conn.provider.runScriptAtomically(conn, sql);
}

/** Applies one migration and records it in the history table. */
export async function applyMigration(conn: Connection, migration: LocalMigration): Promise<void> {
  const provider = conn.provider;
  const q = provider.quote;
  const $ = provider.param;
  const now = provider.now();
  const table = q(HISTORY_TABLE);
  const id = randomUUID();
  await conn.query(
    `INSERT INTO ${table} (id, checksum, migration_name, started_at, applied_steps_count) VALUES (${$(1)}, ${$(2)}, ${$(3)}, ${now}, 0)`,
    [id, migration.checksum, migration.name],
  );
  try {
    await runScript(conn, migration.sql);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    await conn.query(`UPDATE ${table} SET logs = ${$(1)} WHERE id = ${$(2)}`, [message, id]);
    throw new MigrationError(
      'MIGRATION_FAILED',
      `Migration failed to apply. New migrations cannot be applied before the error is recovered from. Fix the cause, then mark it with \`tsorm resolve\`.\n\nMigration name: ${migration.name}\n\n${message}`,
      { cause: error },
    );
  }
  await conn.query(
    `UPDATE ${table} SET finished_at = ${now}, applied_steps_count = 1 WHERE id = ${$(1)}`,
    [id],
  );
}

export async function markApplied(conn: Connection, migration: LocalMigration, failed?: HistoryRow) {
  const provider = conn.provider;
  const q = provider.quote;
  const $ = provider.param;
  const now = provider.now();
  const table = q(HISTORY_TABLE);
  if (failed) await conn.query(`UPDATE ${table} SET rolled_back_at = ${now} WHERE id = ${$(1)}`, [failed.id]);
  await conn.query(
    `INSERT INTO ${table} (id, checksum, migration_name, started_at, finished_at, applied_steps_count) VALUES (${$(1)}, ${$(2)}, ${$(3)}, ${now}, ${now}, 0)`,
    [randomUUID(), migration.checksum, migration.name],
  );
}

export async function markRolledBack(conn: Connection, row: HistoryRow) {
  const provider = conn.provider;
  const $ = provider.param;
  await conn.query(
    `UPDATE ${provider.quote(HISTORY_TABLE)} SET rolled_back_at = ${provider.now()} WHERE id = ${$(1)}`,
    [row.id],
  );
}

/** Serializes migration runs against one database with an advisory lock. */
export async function withLock<T>(conn: Connection, fn: () => Promise<T>): Promise<T> {
  await conn.provider.acquireLock(conn);
  try {
    return await fn();
  } finally {
    await conn.provider.releaseLock(conn);
  }
}
